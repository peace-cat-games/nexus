"""Draw the price sweep as TikZ: one 21 x 21 panel per first move (and one
for the empty board), p1 = 0..20 down, p2 = 0..20 across.  A cell holds the
length of the shortest forced win (turns from the empty board); Black wins are
filled dark with white digits, White wins are open with black digits, and
undecided cells are grey with "?", so the figure reads without colour.

usage: python3 tools/params_figure.py RUNS_JSONL OUT_TEX
"""

import json
import sys

N = 21
STARTS = [("corner", "Black opens in a corner"), ("edge", "Black opens on an edge"),
          ("centre", "Black opens in the centre"), ("empty", "Empty board (best first move)")]


def main():
    rs = [json.loads(l) for l in open(sys.argv[1])]
    by = {(r["p1"], r["p2"], r["start"]): (r["value"], r["within"]) for r in rs}
    for p1 in range(N):
        for p2 in range(N):
            rr = [by.get((p1, p2, s)) for s in ("corner", "edge", "centre")]
            if None in rr:
                continue
            b = [d for v, d in rr if v == "black"]
            if b:
                by[(p1, p2, "empty")] = ("black", min(b))
            elif all(v == "white" for v, _ in rr):
                by[(p1, p2, "empty")] = ("white", max(d for _, d in rr))
            else:
                by[(p1, p2, "empty")] = ("unknown", None)
    out = ["% Generated by nexus/solver/tools/params_figure.py from results/params/runs.jsonl; do not edit."]
    for i, (s, title) in enumerate(STARTS):
        out.append(r"\begin{tikzpicture}[x=0.29cm,y=-0.29cm,font=\fontsize{4.2}{4.2}\selectfont]")
        for p1 in range(N):
            for p2 in range(N):
                v, d = by.get((p1, p2, s), (None, None))
                if v is None:
                    raise SystemExit(f"missing {s} p1={p1} p2={p2}")
                if v == "black":
                    out.append(rf"\fill[black!80] ({p2},{p1}) rectangle ++(1,1); \node[white] at ({p2 + .5},{p1 + .5}) {{{d}}};")
                elif v == "white":
                    out.append(rf"\node at ({p2 + .5},{p1 + .5}) {{{d}}};")
                else:
                    out.append(rf"\fill[black!20] ({p2},{p1}) rectangle ++(1,1); \node at ({p2 + .5},{p1 + .5}) {{?}};")
        out.append(rf"\draw[gray!60,step=1] (0,0) grid ({N},{N}); \draw (0,0) rectangle ({N},{N});")
        for k in range(0, N, 5):
            out.append(rf"\node[font=\scriptsize,above] at ({k + .5},0) {{{k}}}; \node[font=\scriptsize,left] at (0,{k + .5}) {{{k}}};")
        out.append(rf"\node[font=\small,above] at ({N / 2},-2.6) {{{title}}};")
        out.append(rf"\node[font=\scriptsize,above] at ({N / 2},-1.5) {{$p_2\rightarrow$}};")
        out.append(rf"\node[font=\scriptsize,rotate=90,above] at (-1.6,{N / 2}) {{$\leftarrow p_1$}};")
        out.append(r"\end{tikzpicture}" + (r"\hfill" if i % 2 == 0 else r"\\[6pt]"))
    open(sys.argv[2], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
